/**
 * 16x16 pixel icon drawn from a string grid. `#` = [tint], `+` = [tint] at 45% (second tone), `.` = empty.
 * Pixels snap to an integer number of device pixels so edges stay crisp. Unknown keys draw "question".
 * Keys: see [PixelIconKeys].
 */
@Composable
fun PixelIcon(
    icon: String,
    modifier: Modifier = Modifier,
    tint: Color = LocalContentColor.current,
    size: Dp = 24.dp,
    contentDescription: String? = null,
) {
    val glyph = remember(icon) { pixelGlyph(icon) }
    val semantics = if (contentDescription != null) Modifier.semantics { this.contentDescription = contentDescription } else Modifier
    Canvas(modifier.size(size).then(semantics)) { drawPixelGlyph(glyph, tint) }
}

/** Pre-parsed glyph: each run is (row, col, length, tone) packed into 4 ints. */
class PixelGlyph internal constructor(internal val runs: IntArray, val width: Int, val height: Int)

/** Draws [glyph] centred in the draw area, scaled by the largest integer pixel size that fits. */
fun DrawScope.drawPixelGlyph(glyph: PixelGlyph, tint: Color, secondary: Color = tint.copy(alpha = tint.alpha * 0.45f)) {
    val cell = max(1f, floor(minOf(size.width / glyph.width, size.height / glyph.height)))
    val ox = floor((size.width - cell * glyph.width) / 2f)
    val oy = floor((size.height - cell * glyph.height) / 2f)
    drawPixelGlyph(glyph, tint, Offset(ox, oy), cell, secondary)
}

/** Draws [glyph] at [topLeft] with an explicit [cell] size in px. */
fun DrawScope.drawPixelGlyph(glyph: PixelGlyph, tint: Color, topLeft: Offset, cell: Float, secondary: Color = tint.copy(alpha = tint.alpha * 0.45f)) {
    val r = glyph.runs
    var i = 0
    while (i < r.size) {
        drawRect(
            color = if (r[i + 3] == 1) tint else secondary,
            topLeft = Offset(topLeft.x + r[i + 1] * cell, topLeft.y + r[i] * cell),
            size = Size(r[i + 2] * cell, cell),
        )
        i += 4
    }
}

private val glyphCache = HashMap<String, PixelGlyph>()

/** Parsed, cached glyph for [key] (falls back to "question"). */
fun pixelGlyph(key: String): PixelGlyph = synchronized(glyphCache) {
    glyphCache.getOrPut(key) { parse(Grids[key] ?: Grids.getValue("question")) }
}

private fun parse(rows: List<String>): PixelGlyph {
    val runs = ArrayList<Int>()
    rows.forEachIndexed { y, row ->
        var x = 0
        while (x < row.length) {
            val tone = when (row[x]) { '#' -> 1; '+' -> 2; else -> 0 }
            if (tone == 0) { x++; continue }
            val start = x
            while (x < row.length && row[x] == row[start]) x++
            runs += listOf(y, start, x - start, tone)
        }
    }
    return PixelGlyph(runs.toIntArray(), rows.maxOf { it.length }, rows.size)
}

private fun mirror(rows: List<String>) = rows.map { it.reversed() }

