"""Peças da academia do bichinho, desenhadas por código (arte original do projeto), em 1-bit.

Cada peça vira linhas de texto ('1' tinta, '2' xadrez, '.' vazio) em core/.../avatar/GymArt.kt, com a posição no palco
(96 x 76, o bichinho fica no meio e anda por cima das margens). O app desenha o cenário atrás do bichinho; as peças
que o jogador liberou (nível ou troféu, ver GymCatalog) aparecem, as outras não.

    python tools/avatar/gym.py       # escreve GymArt.kt e build/previews/avatar_gym.png
"""
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_KT = os.path.join(ROOT, 'core', 'src', 'main', 'kotlin', 'com', 'ithalo', 'hybridcoach', 'core', 'avatar', 'GymArt.kt')
PREVIEWS = os.path.join(ROOT, 'build', 'previews')
STAGE_W, STAGE_H = 96, 76

INK, DITHER, NONE = 1, 2, 0


class Piece:
    def __init__(self, pid, x, y, w, h, draw):
        self.id, self.x, self.y, self.w, self.h = pid, x, y, w, h
        self.px = [[NONE] * w for _ in range(h)]
        draw(self)

    def set(self, x, y, v=INK):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y][x] = v

    def line(self, x0, y0, x1, y1, v=INK):
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(n + 1):
            self.set(round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n), v)

    def rect(self, x0, y0, x1, y1, v=INK, fill=None):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                edge = x in (x0, x1) or y in (y0, y1)
                if edge:
                    self.set(x, y, v)
                elif fill is not None:
                    self.set(x, y, fill)

    def circle(self, cx, cy, r, v=INK, fill=None):
        for y in range(cy - r, cy + r + 1):
            for x in range(cx - r, cx + r + 1):
                d = (x - cx) ** 2 + (y - cy) ** 2
                if d <= r * r + r * 0.6:
                    inner = d <= (r - 1) ** 2 + (r - 1) * 0.6
                    if not inner:
                        self.set(x, y, v)
                    elif fill is not None:
                        self.set(x, y, fill)

    def dither(self, x0, y0, x1, y1):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if (x + y) % 2 == 0:
                    self.set(x, y, DITHER)

    def rows(self):
        return [''.join('.12'[v] for v in row) for row in self.px]


def window(p):
    p.rect(0, 0, 15, 13)
    p.line(8, 0, 8, 13)
    p.line(0, 7, 15, 7)
    p.dither(1, 1, 7, 6)
    p.line(4, 12, 6, 9, DITHER)


def wall_rack(p):
    for row_y in (4, 10):
        p.line(0, row_y + 2, 13, row_y + 2)
        for x0 in (1, 8):
            p.rect(x0, row_y - 2, x0, row_y + 1)
            p.rect(x0 + 1, row_y - 1, x0 + 4, row_y)
            p.rect(x0 + 5, row_y - 2, x0 + 5, row_y + 1)


def poster(p):
    p.rect(0, 0, 13, 17)
    p.dither(1, 1, 12, 3)
    # a cup
    p.line(4, 6, 9, 6)
    p.line(4, 6, 5, 10)
    p.line(9, 6, 8, 10)
    p.line(5, 10, 8, 10)
    p.line(6, 11, 6, 13)
    p.line(7, 11, 7, 13)
    p.line(4, 14, 9, 14)
    p.line(3, 7, 3, 8)
    p.line(10, 7, 10, 8)


def mirror(p):
    p.rect(0, 2, 11, 27)
    p.rect(1, 3, 10, 26)
    p.line(2, 9, 6, 5, DITHER)
    p.line(2, 14, 8, 8, DITHER)
    p.line(2, 25, 9, 18, DITHER)
    p.line(5, 28, 6, 28)


def bike(p):
    p.circle(13, 12, 5)
    p.dither(10, 9, 15, 14)
    p.line(2, 19, 17, 19)
    p.line(5, 19, 7, 6)
    p.line(4, 5, 9, 5)
    p.line(7, 6, 13, 12)
    p.line(13, 12, 15, 3)
    p.line(13, 3, 17, 3)
    p.line(7, 12, 7, 19)


def treadmill(p):
    p.rect(0, 14, 17, 16)
    p.dither(1, 15, 16, 15)
    p.line(2, 17, 2, 18)
    p.line(15, 17, 15, 18)
    p.line(16, 14, 16, 4)
    p.rect(10, 0, 17, 4)
    p.line(11, 2, 16, 2, DITHER)
    p.line(10, 5, 10, 9)
    p.line(10, 9, 16, 9)


def kettlebell(p):
    p.circle(4, 6, 4)
    p.dither(2, 5, 6, 8)
    p.line(1, 1, 2, 0)
    p.line(2, 0, 6, 0)
    p.line(6, 0, 7, 1)
    p.line(1, 1, 1, 3)
    p.line(7, 1, 7, 3)


PIECES = [
    # id, x, y, w, h, drawer
    ('window', 2, 6, 16, 14, window),
    ('mat', 18, 72, 60, 2, lambda p: (p.line(0, 0, 59, 0), p.dither(1, 1, 58, 1))),
    ('wall_rack', 3, 26, 14, 14, wall_rack),
    ('poster', 80, 6, 14, 18, poster),
    ('bike', 0, 53, 19, 20, bike),
    ('mirror', 83, 22, 12, 29, mirror),
    ('treadmill', 77, 56, 18, 19, treadmill),
    ('kettlebell', 21, 64, 9, 10, kettlebell),
]


def main():
    pieces = [Piece(*spec[:5], spec[5]) for spec in PIECES]
    lines = [
        'package com.ithalo.hybridcoach.core.avatar',
        '',
        '/** The gym pieces behind the pet, generated by tools/avatar/gym.py. Do not edit by hand. */',
        'internal class GymPieceArt(val x: Int, val y: Int, val rows: List<String>)',
        '',
        'internal object GymArt {',
        '    val pieces: Map<String, GymPieceArt> = mapOf(',
    ]
    for p in pieces:
        lines.append('        "%s" to GymPieceArt(%d, %d, listOf(' % (p.id, p.x, p.y))
        for r in p.rows():
            lines.append('            "%s",' % r)
        lines.append('        )),')
    lines += ['    )', '}', '']
    with open(OUT_KT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))

    # preview: every piece, the floor line and the boy at home (the pet clears what is behind it)
    os.makedirs(PREVIEWS, exist_ok=True)
    scale = 5
    img = Image.new('RGB', (STAGE_W * scale, STAGE_H * scale), (212, 204, 184))
    d = ImageDraw.Draw(img)
    ink = (62, 61, 54)

    def put(x, y, v):
        if v == INK or (v == DITHER and (x + y) % 2 == 0):
            d.rectangle([x * scale, y * scale, x * scale + scale - 1, y * scale + scale - 1], fill=ink)

    for x in range(STAGE_W):
        put(x, 74, INK)
        put(x, 75, DITHER)
    for p in pieces:
        for y in range(p.h):
            for x in range(p.w):
                put(p.x + x, p.y + y, p.px[y][x])
    img.save(os.path.join(PREVIEWS, 'avatar_gym.png'))
    print('GymArt.kt: %d pieces' % len(pieces))


if __name__ == '__main__':
    sys.exit(main())
